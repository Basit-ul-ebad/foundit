"""Builds app/lib/firebase_options.dart from a google-services.json file.

Usage: python3 tool/make_firebase_options.py app/android/app/google-services.json app/lib/firebase_options.dart
"""
import json
import sys

PACKAGE = "com.onavri.foundit"

src, dst = sys.argv[1], sys.argv[2]
data = json.load(open(src))
info = data["project_info"]
client = None
for c in data["client"]:
    if c["client_info"]["android_client_info"]["package_name"] == PACKAGE:
        client = c
        break
if client is None:
    sys.exit("No Android app with package " + PACKAGE + " in " + src)

api_key = client["api_key"][0]["current_key"]
app_id = client["client_info"]["mobilesdk_app_id"]
sender = info["project_number"]
project = info["project_id"]
bucket = info.get("storage_bucket", "")

def q(v):
    return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"

out = f"""import 'package:firebase_core/firebase_core.dart';

// Generated by tool/make_firebase_options.py. Do not edit.
const FirebaseOptions? firebaseOptions = FirebaseOptions(
  apiKey: {q(api_key)},
  appId: {q(app_id)},
  messagingSenderId: {q(sender)},
  projectId: {q(project)},
  storageBucket: {q(bucket)},
);
"""
open(dst, "w").write(out)
print("wrote", dst, "for project", project)
